function tr(root) {
  if (LANG != "hi" || !root) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT),
    ns = [];
  while (w.nextNode()) ns.push(w.currentNode);
  ns.forEach((n) => {
    const t = n.nodeValue.trim();
    if (t && HI[t]) n.nodeValue = n.nodeValue.replace(t, HI[t]);
  });
  root.querySelectorAll("[placeholder]").forEach((e) => HI[e.placeholder] && (e.placeholder = HI[e.placeholder]));
}
